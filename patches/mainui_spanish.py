def main():
	plantilla = os.path.join(os.path.dirname(__file__), '..', '3rdparty', 'mainui', 'translations', 'mainui_skeleton_stripped.txt')
	claves = re.findall(r'^"((?:[^"\\]|\\.)*)"\s+""', open(plantilla, encoding='utf-8').read(), re.M)
	faltan = [c for c in claves if c not in ES]
	if faltan:
		print('sin traducir (se quedan en ingles):', faltan)
	lineas = ['// Traduccion al castellano del menu de Xash (mainui).',
		'// Generado por patches/mainui_spanish.py', '"lang"', '{', '"Language" "spanish"', '"Tokens"', '{']
	for k, v in ES.items():
		lineas.append('"%s"\t"%s"' % (k, v.replace('"', '\\"')))
	lineas += ['}', '}', '']
	open(sys.argv[1], 'w', encoding='utf-8', newline='\r\n').write('\n'.join(lineas))
	print('escritas', len(ES), 'cadenas en', sys.argv[1])

if __name__ == '__main__':
	main()
